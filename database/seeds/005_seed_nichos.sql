    n.N,
    ((n.N - 1) / 17) + 1 AS FILA,
    ((n.N - 1) % 17) + 1 AS COLUMNA,
    N'DISPONIBLE'
FROM N
WHERE n.N BETWEEN 1 AND 68
OPTION (MAXRECURSION 200);

