SELECT N'PABELLONES' AS Entidad, COUNT(*) AS Cantidad FROM dbo.PABELLONES
UNION ALL
SELECT N'NICHOS_TOTAL', COUNT(*) FROM dbo.NICHOS
UNION ALL
SELECT N'NICHOS_P1', COUNT(*) FROM dbo.NICHOS n INNER JOIN dbo.PABELLONES p ON p.ID_PABELLON = n.ID_PABELLON WHERE p.CODIGO = N'P1'
UNION ALL
SELECT N'NICHOS_P2', COUNT(*) FROM dbo.NICHOS n INNER JOIN dbo.PABELLONES p ON p.ID_PABELLON = n.ID_PABELLON WHERE p.CODIGO = N'P2'
UNION ALL
SELECT N'NICHOS_P3', COUNT(*) FROM dbo.NICHOS n INNER JOIN dbo.PABELLONES p ON p.ID_PABELLON = n.ID_PABELLON WHERE p.CODIGO = N'P3'
UNION ALL
SELECT N'NICHOS_P4', COUNT(*) FROM dbo.NICHOS n INNER JOIN dbo.PABELLONES p ON p.ID_PABELLON = n.ID_PABELLON WHERE p.CODIGO = N'P4'
UNION ALL
SELECT N'NICHOS_P5', COUNT(*) FROM dbo.NICHOS n INNER JOIN dbo.PABELLONES p ON p.ID_PABELLON = n.ID_PABELLON WHERE p.CODIGO = N'P5';

/* Esperado: 5 pabellones, 292 nichos (68+68+52+52+52) */

SELECT p.CODIGO, MIN(n.NUMERO) AS MinNumero, MAX(n.NUMERO) AS MaxNumero, COUNT(*) AS Total
FROM dbo.NICHOS n
INNER JOIN dbo.PABELLONES p ON p.ID_PABELLON = n.ID_PABELLON
GROUP BY p.CODIGO, p.ORDEN_VISUAL
ORDER BY p.ORDEN_VISUAL;

/* Duplicados (debe devolver 0 filas) */
SELECT ID_PABELLON, NUMERO, COUNT(*) AS Repeticiones
FROM dbo.NICHOS
GROUP BY ID_PABELLON, NUMERO
HAVING COUNT(*) > 1;

GO
