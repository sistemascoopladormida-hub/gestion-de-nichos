/* Ocupaciones — trazabilidad de finalización */
IF COL_LENGTH('dbo.OCUPACIONES_NICHO', 'USUARIO_FINALIZACION') IS NULL
BEGIN
    ALTER TABLE dbo.OCUPACIONES_NICHO ADD USUARIO_FINALIZACION INT NULL;
    ALTER TABLE dbo.OCUPACIONES_NICHO ADD CONSTRAINT FK_OCUP_USUARIO_FIN
        FOREIGN KEY (USUARIO_FINALIZACION) REFERENCES dbo.USUARIOS (ID_USUARIO);
END
GO

IF COL_LENGTH('dbo.OCUPACIONES_NICHO', 'FECHA_MODIFICACION') IS NULL
BEGIN
    ALTER TABLE dbo.OCUPACIONES_NICHO ADD FECHA_MODIFICACION DATETIME2(0) NULL;
END
GO

IF COL_LENGTH('dbo.OCUPACIONES_NICHO', 'CODIGO_MOTIVO_FINALIZACION') IS NULL
BEGIN
    ALTER TABLE dbo.OCUPACIONES_NICHO ADD CODIGO_MOTIVO_FINALIZACION VARCHAR(40) NULL;
END
GO

/* Documentos — baja lógica */
IF COL_LENGTH('dbo.DOCUMENTOS_CEMENTERIO', 'ELIMINADO') IS NULL
BEGIN
    ALTER TABLE dbo.DOCUMENTOS_CEMENTERIO ADD ELIMINADO BIT NOT NULL
        CONSTRAINT DF_DOC_ELIMINADO DEFAULT (0);
END
GO

IF COL_LENGTH('dbo.DOCUMENTOS_CEMENTERIO', 'FECHA_ELIMINACION') IS NULL
BEGIN
    ALTER TABLE dbo.DOCUMENTOS_CEMENTERIO ADD FECHA_ELIMINACION DATETIME2(0) NULL;
END
GO

IF COL_LENGTH('dbo.DOCUMENTOS_CEMENTERIO', 'USUARIO_ELIMINACION') IS NULL
BEGIN
    ALTER TABLE dbo.DOCUMENTOS_CEMENTERIO ADD USUARIO_ELIMINACION INT NULL;
    ALTER TABLE dbo.DOCUMENTOS_CEMENTERIO ADD CONSTRAINT FK_DOC_USUARIO_ELIM
        FOREIGN KEY (USUARIO_ELIMINACION) REFERENCES dbo.USUARIOS (ID_USUARIO);
END
GO
