/* Búsquedas frecuentes */
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_NICHOS_PABELLON_ESTADO' AND object_id = OBJECT_ID(N'dbo.NICHOS'))
    CREATE NONCLUSTERED INDEX IX_NICHOS_PABELLON_ESTADO
        ON dbo.NICHOS (ID_PABELLON, ESTADO)
        INCLUDE (NUMERO, FILA, COLUMNA);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_FALLECIDOS_APELLIDO' AND object_id = OBJECT_ID(N'dbo.FALLECIDOS'))
    CREATE NONCLUSTERED INDEX IX_FALLECIDOS_APELLIDO
        ON dbo.FALLECIDOS (APELLIDO, NOMBRE)
        WHERE ACTIVO = 1;

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_FALLECIDOS_DNI' AND object_id = OBJECT_ID(N'dbo.FALLECIDOS'))
    CREATE NONCLUSTERED INDEX IX_FALLECIDOS_DNI
        ON dbo.FALLECIDOS (DNI)
        WHERE DNI IS NOT NULL;

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_OCUP_FALLECIDO' AND object_id = OBJECT_ID(N'dbo.OCUPACIONES_NICHO'))
    CREATE NONCLUSTERED INDEX IX_OCUP_FALLECIDO
        ON dbo.OCUPACIONES_NICHO (ID_FALLECIDO, ESTADO, FECHA_INICIO DESC);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_OCUP_NICHO' AND object_id = OBJECT_ID(N'dbo.OCUPACIONES_NICHO'))
    CREATE NONCLUSTERED INDEX IX_OCUP_NICHO
        ON dbo.OCUPACIONES_NICHO (ID_NICHO, ESTADO, FECHA_INICIO DESC);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_PREST_VENCIMIENTO' AND object_id = OBJECT_ID(N'dbo.PRESTAMOS_NICHO'))
    CREATE NONCLUSTERED INDEX IX_PREST_VENCIMIENTO
        ON dbo.PRESTAMOS_NICHO (FECHA_VENCIMIENTO, ESTADO);

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_SERV_FECHA' AND object_id = OBJECT_ID(N'dbo.SERVICIOS_CEMENTERIO'))
    CREATE NONCLUSTERED INDEX IX_SERV_FECHA
        ON dbo.SERVICIOS_CEMENTERIO (FECHA_SERVICIO DESC);

/*
  Regla: una sola ocupación ACTIVA por nicho y por fallecido.
*/
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'UX_OCUP_NICHO_ACTIVA' AND object_id = OBJECT_ID(N'dbo.OCUPACIONES_NICHO'))
    CREATE UNIQUE NONCLUSTERED INDEX UX_OCUP_NICHO_ACTIVA
        ON dbo.OCUPACIONES_NICHO (ID_NICHO)
        WHERE ESTADO = 'ACTIVO';

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'UX_OCUP_FALLECIDO_ACTIVA' AND object_id = OBJECT_ID(N'dbo.OCUPACIONES_NICHO'))
    CREATE UNIQUE NONCLUSTERED INDEX UX_OCUP_FALLECIDO_ACTIVA
        ON dbo.OCUPACIONES_NICHO (ID_FALLECIDO)
        WHERE ESTADO = 'ACTIVO';

GO
