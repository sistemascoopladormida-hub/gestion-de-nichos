/** SQL fragment: alias `o` = ocupación activa, `n` = nicho → columna ESTADO_VISUAL */
export const SQL_ESTADO_VISUAL = `
  CASE
    WHEN n.ESTADO IN ('INHABILITADO', 'MANTENIMIENTO', 'RESERVADO') THEN n.ESTADO
    WHEN o.ID_OCUPACION IS NOT NULL AND o.TIPO_OCUPACION = 'OCUPACION_PRESTAMO' THEN 'PRESTAMO'
    WHEN o.ID_OCUPACION IS NOT NULL AND ISNULL(f.DATOS_INCOMPLETOS, 0) = 1 THEN 'OCUPADO_SIN_DATOS'
    WHEN o.ID_OCUPACION IS NOT NULL THEN 'OCUPADO'
    ELSE n.ESTADO
  END
`;

export const SQL_JOIN_OCUPACION_ACTIVA = `
  LEFT JOIN dbo.OCUPACIONES_NICHO o
    ON o.ID_NICHO = n.ID_NICHO AND o.ESTADO = 'ACTIVO'
  LEFT JOIN dbo.FALLECIDOS f ON f.ID_FALLECIDO = o.ID_FALLECIDO
`;
